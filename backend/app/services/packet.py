"""Evidence packet builder (F13). The factual sections are generated in code from the database;
the LLM only contributes the narrative paragraph."""
from app.models import Assessment, Dispute, Message, Order, Shipment


def build_packet(dispute: Dispute, order: Order | None, shipment: Shipment | None, messages: list[Message], assessment: Assessment | None, narrative: str, policy_text: str) -> str:
    lines = [
        f"# Seller response: dispute {dispute.paypal_dispute_id}",
        f"Internal case {dispute.id} | Reason: {dispute.reason.replace('_', ' ').title()} | Amount: {dispute.amount} {dispute.currency}",
    ]
    if dispute.simulated:
        lines.append("**SIMULATED PACKET: generated by the Verdict prototype from seeded demo data.**")
    lines += ["", "## Summary", narrative.strip() or "The merchant fulfilled this order as described below.", "", "## Order"]
    if order and order.ship_address != "Unknown":
        items = ", ".join(f"{i.get('qty', 1)} x {i.get('name', 'item')}" for i in (order.items_json or [])) or "n/a"
        lines += [f"- Customer: {order.customer_name}", f"- Items: {items}", f"- Ship-to address: {order.ship_address}", f"- Shipping policy accepted at checkout: {'yes' if order.policy_accepted else 'no'}"]
    else:
        lines.append("- No matching order record was found.")
    lines += ["", "## Delivery"]
    if shipment:
        lines += [f"- Carrier: {shipment.carrier}", f"- Tracking number: {shipment.tracking}", f"- Status: {shipment.status}", f"- Delivered at: {shipment.delivered_at:%b %d, %Y}" if shipment.delivered_at else "- Delivered at: unknown", f"- Delivery address: {shipment.delivery_address}", f"- Proof of delivery: {shipment.proof_url or 'none on file'}"]
    else:
        lines.append("- No shipment record on file.")
    lines += ["", "## Customer communication"]
    lines += [f"- [{m.ts:%Y-%m-%d %H:%M}] {m.sender}: {m.text}" for m in messages] or ["- No messages on file."]
    lines += ["", "## Merchant policy", policy_text]
    if assessment:
        lines += ["", "## Evidence checklist"] + [f"- {'[x]' if i['present'] else '[ ]'} {i['type'].replace('_', ' ').title()}: {i['note']}" for i in assessment.evidence_json]
    return "\n".join(lines)
